export const applyTheme = (themeName, progressPercent = 0) => {
  const theme = themes[themeName];
  if (!theme) return;

  const root = document.documentElement;
  
  // Aplicar variáveis CSS
  root.style.setProperty('--theme-background', theme.background);
  root.style.setProperty('--theme-card-bg', theme.card.background);
  root.style.setProperty('--theme-card-border', theme.card.border);
  root.style.setProperty('--theme-card-border-left', theme.card.borderLeft);
  root.style.setProperty('--theme-card-color', theme.card.color);
  
  root.style.setProperty('--theme-done-bg', theme.done.background);
  root.style.setProperty('--theme-done-border', theme.done.border);
  root.style.setProperty('--theme-done-border-left', theme.done.borderLeft);
  
  root.style.setProperty('--theme-editing-bg', theme.editing.background);
  root.style.setProperty('--theme-editing-border', theme.editing.border);
  root.style.setProperty('--theme-editing-border-left', theme.editing.borderLeft);
  
  root.style.setProperty('--theme-btn-close-bg', theme.buttons.close.background);
  root.style.setProperty('--theme-btn-close-color', theme.buttons.close.color);
  root.style.setProperty('--theme-btn-edit-bg', theme.buttons.edit.background);
  root.style.setProperty('--theme-btn-edit-color', theme.buttons.edit.color);
  root.style.setProperty('--theme-btn-archive-bg', theme.buttons.archive.background);
  root.style.setProperty('--theme-btn-archive-color', theme.buttons.archive.color);
  root.style.setProperty('--theme-btn-clear-bg', theme.buttons.clear.background);
  root.style.setProperty('--theme-btn-clear-border', theme.buttons.clear.border);
  root.style.setProperty('--theme-btn-clear-color', theme.buttons.clear.color);
  
  root.style.setProperty('--theme-progress-bg', theme.progress.background);
  root.style.setProperty('--theme-progress-border', theme.progress.border);
  root.style.setProperty('--theme-progress-bar', theme.progress.bar);

  // Aplicar background dinâmico no body baseado no progresso
  const dynamicBackground = getDynamicBackground(themeName, progressPercent);
  document.body.style.background = dynamicBackground;
  
  // Salvar tema no localStorage
  localStorage.setItem('selectedTheme', themeName);
};

export const getCurrentTheme = () => {
  return localStorage.getItem('selectedTheme') || 'green-red-high';
};

export const getDynamicBackground = (themeName, progressPercent) => {
  const theme = themes[themeName];
  if (!theme) return theme.background;
  
  // Para cada tema, criar variações baseadas no progresso
  switch(themeName) {
    case 'green-red-high':
      return `linear-gradient(to right, rgb(00, 50, 00) ${-100 + progressPercent*2}%, rgb(58, 0, 0))`;
    
    case 'ocean-blue':
      const blueIntensity = 15 + (progressPercent * 0.2);
      return `linear-gradient(135deg, hsl(215, 65%, ${blueIntensity}%) 0%, hsl(215, 70%, ${25 + progressPercent/5}%) 100%)`;
    
    case 'sunset-orange':
      const orangeIntensity = 12 + (progressPercent * 0.15);
      return `linear-gradient(135deg, hsl(25, 50%, ${orangeIntensity}%) 0%, hsl(25, 55%, ${20 + progressPercent/6}%) 100%)`;
    
    case 'purple-dark':
      const purpleIntensity = 14 + (progressPercent * 0.18);
      return `linear-gradient(135deg, hsl(260, 25%, ${purpleIntensity}%) 0%, hsl(260, 30%, ${22 + progressPercent/5}%) 100%)`;
    
    case 'dark-modern':
      const grayIntensity = 15 + (progressPercent * 0.15);
      return `linear-gradient(135deg, hsl(0, 0%, ${grayIntensity}%) 0%, hsl(240, 5%, ${20 + progressPercent/5}%) 100%)`;
    
    case 'monokai':
      const monokaiIntensity = 15 + (progressPercent * 0.1);
      return `linear-gradient(135deg, hsl(60, 10%, ${monokaiIntensity}%) 0%, hsl(60, 15%, ${20 + progressPercent/6}%) 100%)`;
    
    case 'dracula':
      const draculaIntensity = 22 + (progressPercent * 0.12);
      return `linear-gradient(135deg, hsl(231, 15%, ${draculaIntensity}%) 0%, hsl(232, 14%, ${28 + progressPercent/7}%) 100%)`;
    
    default:
      return theme.background;
  }
};
